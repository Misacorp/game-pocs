import { chromium } from 'playwright';
const quality = process.argv[2] || 'high';
const exe = '/opt/pw-browsers/chromium';
const browser = await chromium.launch({ executablePath: exe, args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto('http://localhost:5213/');
await page.waitForTimeout(1200);
await page.evaluate((q) => localStorage.setItem('driftwake:gfx', JSON.stringify(q)), quality);
await page.click('text=Play');
await page.waitForTimeout(500);
await page.click('text=Create New');
await page.waitForTimeout(400);
await page.click('text=Vanguard');
await page.waitForTimeout(200);
await page.click('input');
await page.keyboard.type(`Fps${quality}`);
await page.click('button:text-is("Create")');
await page.waitForFunction(() => window.__session?.state?.mapId === 'driftmoor_town', null, { timeout: 20000 });
const frame0 = await page.evaluate(() => window.__game.loop.frame).catch(() => 0);
const t0 = Date.now();
await page.waitForTimeout(6000);
const frame1 = await page.evaluate(() => window.__game.loop.frame);
const elapsed = Date.now() - t0;
const fps = await page.evaluate(() => window.__game.loop.actualFps);
console.log(`QUALITY=${quality} ticks=${frame1 - frame0} elapsedMs=${elapsed} ticksPerSec=${((frame1 - frame0) / (elapsed / 1000)).toFixed(2)} reportedFps=${fps.toFixed(2)}`);
await browser.close();
